#!/usr/bin/env python3
"""Copy the helper prelude of a lifted PPU source (everything before its first
lifted function) into an include file, so native replacements use exactly the
lifted code's FP, rotate and trampoline helpers.

usage: lifted_prelude.py LIFTED_SOURCE OUTPUT
"""
import re
import sys

FUNC_RE = re.compile(r'^void func_[0-9A-Fa-f]{8}\(ppu_context\* ctx\) \{$')


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, dst = sys.argv[1], sys.argv[2]
    out = ['/* Generated by scripts/lifted_prelude.py from %s -- do not edit. */'
           % src.replace('\\', '/').rsplit('/', 1)[-1]]
    for line in open(src, encoding='utf-8', errors='surrogateescape'):
        if FUNC_RE.match(line.rstrip('\n')):
            break
        out.append(line.rstrip('\n'))
    else:
        sys.exit('lifted_prelude.py: no lifted function in ' + src)
    open(dst, 'w', encoding='utf-8', errors='surrogateescape', newline='\n').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
